export function errorText(error:unknown,t:Translator,fallback:Key):string {
  if(error instanceof TranslationError)return t(error.key,error.values);
  const message=error instanceof Error?error.message:typeof error==='string'?error:'';
  const numeric=message.match(/^(.+) must be (a finite number|between (-?\d+(?:\.\d+)?) and (-?\d+(?:\.\d+)?))\.$/);
  if(numeric&&Object.hasOwn(fillValidationLabels,numeric[1])){
    const v0=t(fillValidationLabels[numeric[1]]);
    return numeric[2]==='a finite number'?t('{v0} must be a finite number.',{v0}):t('{v0} must be between {v1} and {v2}.',{v0,v1:Number(numeric[3]),v2:Number(numeric[4])});
  }
  const key=Object.hasOwn(en,message)?message as Key:(Object.keys(tr) as Key[]).find(key=>tr[key]===message);
  return t(key??fallback);
}
