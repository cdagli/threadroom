import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {EventEmitter} from 'node:events';
import {runInNewContext} from 'node:vm';

function launcher() {
  const calls=[], lines=new EventEmitter(), process=new EventEmitter(), watchers=[], timers=new Map();
  let timerId=0;
  process.env={};process.execPath='/node';
  const source=readFileSync(new URL('../scripts/dev.mjs',import.meta.url),'utf8').replace(/^import .*;\n/gm,'');
  runInNewContext(source,{
    process,existsSync:()=>true,createInterface:({input})=>input.lines,
    watch(directory,options,callback){const watcher=new EventEmitter();watcher.close=()=>{watcher.closed=true;};watchers.push({directory,callback,watcher});return watcher;},
    console:{log(){},error(){}},setTimeout(callback,ms){const id=++timerId;timers.set(id,{callback,ms});return id;},clearTimeout(id){timers.delete(id);},
    spawn(command,args,options){
      const child=new EventEmitter();child.stdout={lines:calls.length?new EventEmitter():lines};child.killed=false;
      child.kill=()=>{child.killed=true;};calls.push({command,args,options,child});return child;
    }
  });
  return {calls,lines,process,watchers,flushReload(){for(const [id,timer] of timers)if(timer.ms===150){timers.delete(id);timer.callback();}}};
}

test('Next waits for Python and proxies its actual bound port',()=>{
  const app=launcher();
  assert.equal(app.calls.length,1);
  app.lines.emit('line','Starting Python…');
  assert.equal(app.calls.length,1);
  app.lines.emit('line',JSON.stringify({threadroomReady:true,port:49321}));
  assert.equal(app.calls.length,2);
  assert.equal(app.calls[1].options.env.THREADROOM_LOCAL_API,'http://127.0.0.1:49321');
  assert.equal(app.calls[1].options.env.THREADROOM_API_PORT,'49321');
  app.lines.emit('line',JSON.stringify({threadroomReady:true,port:12345}));
  assert.equal(app.calls.length,2);
});

test('Python failure prevents a disconnected web server',()=>{
  const app=launcher();app.calls[0].child.emit('exit',1);
  assert.equal(app.process.exitCode,1);
  assert.equal(app.calls.length,1);
  app.lines.emit('line',JSON.stringify({threadroomReady:true,port:49321}));
  assert.equal(app.calls.length,1);
});

test('Python failure shuts down an already running web server',()=>{
  const app=launcher();app.lines.emit('line',JSON.stringify({threadroomReady:true,port:49321}));
  app.calls[0].child.emit('exit',1);
  assert.equal(app.process.exitCode,1);
  assert.equal(app.calls[1].child.killed,true);
});

test('Backend edits restart Python on the same port without restarting Next',()=>{
  const app=launcher();app.lines.emit('line',JSON.stringify({threadroomReady:true,port:49321}));
  const python=app.calls[0],web=app.calls[1];
  const change=app.watchers.find(w=>w.directory==='embroidery').callback;
  change('change','patterns.py');change('change','fill-patterns.json');app.flushReload();
  assert.equal(python.child.killed,true);
  assert.equal(web.child.killed,false);
  assert.equal(app.calls.length,2,'wait until the old process releases its port');
  python.child.emit('exit',null);
  assert.equal(app.calls.length,3,'multiple edits debounce into one restart');
  const restarted=app.calls[2];
  assert.equal(restarted.options.env.THREADROOM_API_PORT,'49321');
  restarted.child.stdout.lines.emit('line',JSON.stringify({threadroomReady:true,port:49321}));
  assert.equal(app.calls.length,3,'readiness does not launch a second Next process');
  restarted.child.emit('exit',1);
  assert.equal(app.process.exitCode,1,'unexpected failure after a reload is still fatal');
  assert.equal(web.child.killed,true);
});

test('Generated bytecode does not reload Python, and shutdown closes watchers',()=>{
  const app=launcher();app.lines.emit('line',JSON.stringify({threadroomReady:true,port:49321}));
  for(const watcher of app.watchers)watcher.callback('change','__pycache__/compiler.cpython-312.pyc');
  app.flushReload();assert.equal(app.calls[0].child.killed,false);
  app.watchers[0].callback('change','export.py');
  app.process.emit('SIGINT');app.flushReload();app.calls[0].child.emit('exit',null);
  assert.equal(app.calls.length,2,'pending reload must not respawn during shutdown');
  assert.ok(app.watchers.every(w=>w.watcher.closed));
});
