"""Generate the thread catalogues from Ember's colour chart.

Run with .venv/bin/python scripts/generate-threads.py path/to/colors.json from the worktree root.
colors.json is https://v2.emberdesign.net/colors.json ({brand: [{code, color, rgb:{r,g,b}}]}).
Writes lib/threads.ts (brand list + inline Brother Embroidery chart), public/threads/<id>.json
(other brands, loaded on demand) and embroidery/threads.json (brand ids and the Brother chart
for the compiler).
"""
import json
import re
import sys
from pathlib import Path

SOURCE = 'Ember Design thread charts (v2.emberdesign.net/colors.json)'
# Ember chart name -> label shown in Threadroom. Non-thread charts are skipped.
RENAME = {'BROTHER Country': 'Brother Embroidery', 'MADEIRA Rayon': 'Madeira Rayon',
          'Sulky Holoshimmmer 30': 'Sulky Holoshimmer 30'}
SKIP = {'Applique', 'Default'}
DEFAULT = 'brother'

charts = json.loads(Path(sys.argv[1]).read_text())
brands = []
for chart, colours in charts.items():
    if chart in SKIP:
        continue
    label = RENAME.get(chart, chart)
    brand = DEFAULT if chart == 'BROTHER Country' else re.sub(r'[^a-z0-9]+', '-', label.lower()).strip('-')
    seen, threads = set(), []
    for c in colours:
        code = str(c['code']).strip()
        if not code or code in seen:
            continue
        seen.add(code)
        rgb = c['rgb']
        threads.append([code, (c.get('color') or '').strip(), '#%02x%02x%02x' % (rgb['r'], rgb['g'], rgb['b'])])
    brands.append({'id': brand, 'label': label, 'count': len(threads), 'threads': threads})
brands.sort(key=lambda b: (b['id'] != DEFAULT, b['label'].lower()))
assert len({b['id'] for b in brands}) == len(brands)

out = Path('public/threads')
out.mkdir(parents=True, exist_ok=True)
for old in out.glob('*.json'):
    old.unlink()
for b in brands[1:]:
    (out/f"{b['id']}.json").write_text(json.dumps(b['threads'], separators=(',', ':'))+'\n')
Path('embroidery/threads.json').write_text(json.dumps({'source': SOURCE, 'brands': [{'id': b['id'], 'label': b['label']} for b in brands],
                                                   'brother': brands[0]['threads']}, indent=1)+'\n')

brother = brands[0]
path = Path('lib/threads.ts')
rest = path.read_text().split('// Colour math', 1)[1]
path.write_text('// Generated by scripts/generate-threads.py from '+SOURCE+'.\n'
                '// Brother Embroidery thread (retail spool numbers) is inline; other charts load from public/threads/<id>.json.\n'
                'export const threadBrands = [\n'+''.join('  '+json.dumps({'id': b['id'], 'label': b['label'], 'count': b['count']})+',\n' for b in brands)+'] as const;\n'
                'export const brotherThreads = [\n'+''.join('  '+json.dumps({'code': c, 'name': n, 'color': h})+',\n' for c, n, h in brother['threads'])+'] as const;\n\n'
                '// Colour math'+rest)
print(len(brands), 'brands,', sum(b['count'] for b in brands), 'threads')
