"""Run with .venv/bin/python scripts/generate-threads.py from the worktree root."""
import json
from pathlib import Path
from pystitch.EmbThreadPec import get_thread_set

source = 'pystitch 1.0.1, EmbThreadPec.get_thread_set(); PEC indices 1–64 (not retail spool numbers).'
threads = [{"code": t.catalog_number, "name": t.description,
            "rgb": [t.get_red(), t.get_green(), t.get_blue()], "color": t.hex_color()}
           for t in get_thread_set() if t is not None]
assert len(threads) == 64
Path('embroidery/threads.json').write_text(json.dumps({"source": source, "threads": threads}, indent=2)+'\n')
path = Path('lib/threads.ts')
math = path.read_text().split('// Colour math', 1)[1] if path.exists() else ''
path.write_text('// Generated by scripts/generate-threads.py from '+source+'\n'
                'export const brotherThreads = [\n'+''.join('  '+json.dumps(t)+',\n' for t in threads)+'] as const;\n\n// Colour math'+math)
