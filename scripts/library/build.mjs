// Builds the generated library motifs.
//   node scripts/library/build.mjs            rebuild every motif
//   node scripts/library/build.mjs bee fish   rebuild motifs whose id matches any word
// Sources: scripts/library/motifs/<category>/<slug>.mjs (one motif each, default export from kit.motif).
// Output:  lib/library-samples/motifs/<id>.json and a generated index.ts that the catalog imports.
import {readdirSync,writeFileSync,mkdirSync,rmSync,existsSync} from 'node:fs';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {builder} from './kit.mjs';
import {load} from '../../tests/load-lib.mjs';
const {validLibraryAsset,libraryCategories}=load('library');

const root=fileURLToPath(new URL('../..',import.meta.url));
const sourceDir=path.join(root,'scripts/library/motifs'),outDir=path.join(root,'lib/library-samples/motifs');
const words=process.argv.slice(2);
const sources=readdirSync(sourceDir,{withFileTypes:true}).filter(d=>d.isDirectory())
  .flatMap(d=>readdirSync(path.join(sourceDir,d.name)).filter(f=>f.endsWith('.mjs')).map(f=>({category:d.name,slug:f.slice(0,-4),file:path.join(sourceDir,d.name,f)})))
  .sort((a,b)=>`${a.category}.${a.slug}`.localeCompare(`${b.category}.${b.slug}`));

mkdirSync(outDir,{recursive:true});
const ids=new Set(),errors=[];let built=0;
for(const s of sources){
  const id=`${s.category}.${s.slug}`;ids.add(id);
  if(words.length&&!words.some(w=>id.includes(w)))continue;
  const def=(await import(pathToFileURL(s.file).href)).default;
  if(def?.id!==id){errors.push(`${s.file}: id must be '${id}' (category folder + file name), got '${def?.id}'`);continue;}
  if(!libraryCategories.some(c=>c.id===def.categoryId)||def.categoryId!==s.category){errors.push(`${id}: categoryId must be '${s.category}'`);continue;}
  const b=builder(s.slug);
  const asset={version:1,id,categoryId:def.categoryId,name:def.name,tags:def.tags,design:{objects:def.draw(b),groups:[{id:b.group,name:def.groupName}]}};
  if(!validLibraryAsset(asset)){errors.push(`${id}: invalid library asset (check kinds, widths, thread codes and point limits)`);continue;}
  writeFileSync(path.join(outDir,`${id}.json`),JSON.stringify(asset)+'\n');built++;
}
// Full builds drop output whose source was deleted or renamed.
if(!words.length)for(const f of readdirSync(outDir))if(f.endsWith('.json')&&!ids.has(f.slice(0,-5)))rmSync(path.join(outDir,f));
const listed=[...ids].filter(id=>existsSync(path.join(outDir,`${id}.json`)));
const index=`// Generated by scripts/library/build.mjs from scripts/library/motifs. Do not edit.\n${listed.map((id,i)=>`import m${i} from './${id}.json';`).join('\n')}\n\nexport const generatedMotifs=[${listed.map((_,i)=>`m${i}`).join(',')}];\n`;
writeFileSync(path.join(outDir,'index.ts'),index);
console.log(`built ${built} of ${sources.length} motifs; index lists ${listed.length}`);
if(errors.length){console.error(errors.join('\n'));process.exit(1);}
